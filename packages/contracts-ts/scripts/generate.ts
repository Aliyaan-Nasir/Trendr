/**
 * Generates src/abis.ts from Foundry artifacts and src/deployments.ts from
 * contracts/deployments/*.json. Run `forge build` in contracts/ first, then `bun run generate`.
 */
import { readdirSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..", "..", "contracts");
const contracts = [
  "TrendRegistry",
  "TrendrLens",
  "OutcomeMarkets",
  "OutcomeToken",
  "OutcomeListing",
  "TrendrSpot",
  "AttentionPerp",
  "BondingCurve",
  "TrendCoin",
  "KuruGraduationVenue",
  "CurationFees",
  "PasskeyAccount",
  "PerplOrderGuard",
  "IKuruRouter",
  "IKuruOrderBook",
  "IKuruVault",
  "IKuruMarginAccount",
];

let abis = "// Generated by scripts/generate.ts from Foundry artifacts. Do not edit.\n\n";
for (const name of contracts) {
  const dir = readdirSync(join(root, "out")).find((d) => d.endsWith(".sol") && readdirSync(join(root, "out", d)).includes(`${name}.json`));
  if (!dir) throw new Error(`no artifact for ${name}; run forge build`);
  const artifact = await Bun.file(join(root, "out", dir, `${name}.json`)).json();
  const id = name.charAt(0).toLowerCase() + name.slice(1);
  abis += `export const ${id}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
await Bun.write(join(import.meta.dir, "..", "src", "abis.ts"), abis.trimEnd() + "\n");

let deployments = "// Generated by scripts/generate.ts from contracts/deployments. Do not edit.\n\n";
deployments += "export interface Deployment {\n  chainId: number;\n  startBlock: number;\n  creMode: string;\n";
const keys = ["ausd", "trendRegistry", "trendrLens", "outcomeMarkets", "outcomeListing", "trendrSpot", "attentionPerp", "bondingCurve", "kuruGraduationVenue", "curationFees", "passkeyAccount", "perplOrderGuard", "kuruRouter", "perplExchange", "creForwarder", "treasury"];
for (const k of keys) deployments += `  ${k}: \`0x\${string}\`;\n`;
deployments += "  /** perplOrderGuard's leverage cap for session Perpl openings, in hundredths (1000 is 10x); 0 without Perpl. */\n";
deployments += "  perplSessionMaxLeverageHdths: number;\n";
deployments += "}\n\nexport const deployments: Record<number, Deployment> = {\n";
// Local chains (31337) are ephemeral: their addresses are passed in at runtime, never published.
const published = readdirSync(join(root, "deployments")).filter((f) => f.endsWith(".json") && f !== "31337.json");
for (const file of published.sort()) {
  const d = await Bun.file(join(root, "deployments", file)).json();
  deployments += `  ${d.chainId}: ${JSON.stringify(d, null, 2).replace(/\n/g, "\n  ")} as Deployment,\n`;
}
deployments += "};\n";
await Bun.write(join(import.meta.dir, "..", "src", "deployments.ts"), deployments);
console.log("generated abis.ts and deployments.ts");
