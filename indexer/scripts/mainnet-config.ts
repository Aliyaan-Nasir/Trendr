/**
 * Writes the Mainnet indexer's config from config.yaml and contracts/deployments/143.json:
 * - config.mainnet.yaml: config.yaml's settings and contracts verbatim, with one chain, Monad
 *   Mainnet (143), at the deployment's addresses and start block. Run it with
 *   ENVIO_CONFIG=config.mainnet.yaml, as its own indexer with its own database.
 * - src/lib/mainnet.ts: the PasskeyAccount implementation Mainnet accounts delegate to.
 * `--check` writes nothing and fails when either file is out of date.
 *
 *   node --experimental-strip-types scripts/mainnet-config.ts [--deployment <path>] [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const MAINNET = 143;
const ADDRESS = /^0x[0-9a-fA-F]{40}$/;
const ZERO = /^0x0{40}$/;

/** The deployment keys each configured contract takes its address from; null for contracts registered at runtime. */
export const CONTRACT_ADDRESSES: Record<string, string | null> = {
  TrendRegistry: "trendRegistry",
  OutcomeMarkets: "outcomeMarkets",
  OutcomeListing: "outcomeListing",
  TrendrToken: null,
  AttentionPerp: "attentionPerp",
  BondingCurve: "bondingCurve",
  KuruGraduationVenue: "kuruGraduationVenue",
  CurationFees: "curationFees",
  TrendrSpot: "trendrSpot",
  KuruRouter: "kuruRouter",
  KuruOrderBook: null,
  PasskeyAccount: null,
  PerplExchange: "perplExchange",
};

export type Deployment = Record<string, unknown> & { chainId: number; startBlock: number; passkeyAccount: string };

/** config.yaml split at its top-level `chains:` key: everything before it, and the contracts it declares. */
function shared(configYaml: string): { head: string; contracts: string[] } {
  const at = configYaml.search(/^chains:/m);
  if (at < 0) throw new Error("config.yaml has no chains section");
  const head = configYaml.slice(0, at);
  const block = head.slice(head.search(/^contracts:/m));
  const contracts = [...block.matchAll(/^ {2}- name: (\w+)\s*$/gm)].map((m) => m[1]!);
  if (contracts.length === 0) throw new Error("config.yaml declares no contracts");
  return { head, contracts };
}

function address(d: Deployment, key: string): string {
  const a = d[key];
  if (typeof a !== "string" || !ADDRESS.test(a) || ZERO.test(a)) throw new Error(`the deployment has no ${key}`);
  return a;
}

export function renderConfig(configYaml: string, d: Deployment): string {
  if (d.chainId !== MAINNET) throw new Error(`the deployment is for chain ${d.chainId}, not Mainnet (${MAINNET})`);
  if (!Number.isInteger(d.startBlock) || d.startBlock <= 0) throw new Error("the deployment has no startBlock");
  const { head, contracts } = shared(configYaml);
  const lines = [
    "chains:",
    "  # Monad Mainnet. Addresses and the start block come from contracts/deployments/143.json.",
    `  - id: ${MAINNET}`,
    "    # The deployment's first block unless ENVIO_START_BLOCK_143 starts later (see config.yaml).",
    `    start_block: \${ENVIO_START_BLOCK_${MAINNET}:-${d.startBlock}}`,
    "    # HyperSync backfills history; a plain RPC follows the head (see config.yaml).",
    "    rpc:",
    `      - url: \${ENVIO_RPC_URL_${MAINNET}:-https://rpc.monad.xyz}`,
    "        for: realtime",
    "        interval_ceiling: 10",
    "    contracts:",
  ];
  for (const name of contracts) {
    if (!(name in CONTRACT_ADDRESSES))
      throw new Error(`config.yaml declares ${name}, which scripts/mainnet-config.ts does not map to the deployment`);
    lines.push(`      - name: ${name}`);
    const key = CONTRACT_ADDRESSES[name];
    if (key) lines.push(`        address: "${address(d, key)}"`);
  }
  const [schemaLine, ...rest] = head.split("\n");
  const banner = [
    "# Generated by `pnpm mainnet:config` from config.yaml and contracts/deployments/143.json. Do not edit:",
    "# change config.yaml and regenerate. The Mainnet indexer runs with ENVIO_CONFIG=config.mainnet.yaml.",
  ];
  const top = schemaLine?.startsWith("# yaml-language-server")
    ? [schemaLine, ...banner, ...rest]
    : [...banner, schemaLine ?? "", ...rest];
  return `${top.join("\n")}${lines.join("\n")}\n`;
}

/** src/lib/mainnet.ts for a deployment, or for none yet. */
export function renderConstants(d: Deployment | null): string {
  const impl = d ? `"${address(d, "passkeyAccount").toLowerCase()}"` : "";
  return [
    "// Generated by `pnpm mainnet:config` from contracts/deployments/143.json. Do not edit by hand.",
    "",
    "/** PasskeyAccount implementations that Trendr accounts on Monad Mainnet delegate to; none before the deploy. */",
    `export const MAINNET_PASSKEY_ACCOUNTS: readonly string[] = [${impl}];`,
    "",
  ].join("\n");
}

const here = dirname(fileURLToPath(import.meta.url));
export const PATHS = {
  config: join(here, "..", "config.yaml"),
  mainnetConfig: join(here, "..", "config.mainnet.yaml"),
  constants: join(here, "..", "src", "lib", "mainnet.ts"),
  deployment: join(here, "..", "..", "contracts", "deployments", `${MAINNET}.json`),
};

function main(argv: string[]) {
  const i = argv.indexOf("--deployment");
  const source = i >= 0 && argv[i + 1] ? resolve(argv[i + 1]!) : PATHS.deployment;
  if (!existsSync(source)) throw new Error(`no ${source}: deploy the contracts to Mainnet first`);
  const d = JSON.parse(readFileSync(source, "utf8")) as Deployment;
  const outputs = [
    [PATHS.mainnetConfig, renderConfig(readFileSync(PATHS.config, "utf8"), d)],
    [PATHS.constants, renderConstants(d)],
  ] as const;
  const stale = outputs
    .filter(([file, text]) => !existsSync(file) || readFileSync(file, "utf8") !== text)
    .map(([file]) => file);
  if (argv.includes("--check")) {
    if (stale.length > 0) {
      console.error(`out of date with ${source}: ${stale.join(", ")}; run pnpm mainnet:config`);
      process.exit(1);
    }
    console.log("config.mainnet.yaml and src/lib/mainnet.ts match the deployment");
    return;
  }
  for (const [file, text] of outputs) writeFileSync(file, text);
  console.log(`wrote config.mainnet.yaml (start block ${d.startBlock}) and src/lib/mainnet.ts from ${source}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
