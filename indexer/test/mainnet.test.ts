import { copyFileSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { createTestIndexer } from "envio";
import { afterAll, describe, it } from "vitest";
import { CONTRACT_ADDRESSES, type Deployment, PATHS, renderConfig, renderConstants } from "../scripts/mainnet-config";
import { chainConstants } from "../src/lib/constants";
import { MAINNET_PASSKEY_ACCOUNTS } from "../src/lib/mainnet";

/** A Mainnet deployment as Deploy.s.sol writes it (made-up Trendr addresses, real externals). */
const DEPLOYMENT: Deployment = {
  chainId: 143,
  startBlock: 112_100_000,
  creMode: "mock",
  ausd: "0x00000000eFE302BEAA2b3e6e1b18d08D69a9012a",
  trendRegistry: "0x5aA1000000000000000000000000000000000001",
  curationFees: "0x5aA1000000000000000000000000000000000002",
  outcomeMarkets: "0x5aA1000000000000000000000000000000000003",
  outcomeListing: "0x5aA1000000000000000000000000000000000004",
  attentionPerp: "0x5aA1000000000000000000000000000000000005",
  bondingCurve: "0x5aA1000000000000000000000000000000000006",
  kuruGraduationVenue: "0x5aA1000000000000000000000000000000000007",
  passkeyAccount: "0x5aA1000000000000000000000000000000000008",
  trendrLens: "0x5aA1000000000000000000000000000000000009",
  treasury: "0x5aA100000000000000000000000000000000000a",
  trendrSpot: "0x5aA100000000000000000000000000000000000b",
  kuruRouter: "0xd651346d7c789536ebf06dc72aE3C8502cd695CC",
  perplExchange: "0x34B6552d57a35a1D042CcAe1951BD1C370112a6F",
  creForwarder: "0x9eF6468C5f37b976E57d52054c693269479A784d",
};

const configYaml = readFileSync(PATHS.config, "utf8");
const rendered = renderConfig(configYaml, DEPLOYMENT);

// The test indexer below runs on a Mainnet config generated from DEPLOYMENT. Envio reads the config
// named by ENVIO_CONFIG when an indexer is created, and the schema from the config's directory.
const dir = mkdtempSync(join(tmpdir(), "trendr-indexer-mainnet-"));
writeFileSync(join(dir, "config.mainnet.yaml"), rendered);
copyFileSync(join(dirname(PATHS.config), "schema.graphql"), join(dir, "schema.graphql"));
process.env.ENVIO_CONFIG = join(dir, "config.mainnet.yaml");
afterAll(() => {
  delete process.env.ENVIO_CONFIG;
  rmSync(dir, { recursive: true, force: true });
});

describe("Mainnet config", () => {
  it("is config.yaml's settings and contracts with one chain, Mainnet, at the deployment's addresses", (t) => {
    const at = (text: string) => text.search(/^chains:/m);
    const banner = /^# Generated by .*\n# change config\.yaml .*\n/m;
    t.expect(rendered.slice(0, at(rendered)).replace(banner, "")).toBe(configYaml.slice(0, at(configYaml)));

    const chains = rendered.slice(at(rendered));
    t.expect([...chains.matchAll(/^ {2}- id: (\d+)$/gm)].map((m) => m[1])).toEqual(["143"]);
    t.expect(chains).toContain("    start_block: ${ENVIO_START_BLOCK_143:-112100000}\n");
    t.expect(chains).toContain("      - url: ${ENVIO_RPC_URL_143:-https://rpc.monad.xyz}\n");
    for (const [name, key] of Object.entries(CONTRACT_ADDRESSES)) {
      const entry = key
        ? `      - name: ${name}\n        address: "${DEPLOYMENT[key]}"\n`
        : `      - name: ${name}\n      - `;
      if (name !== "PerplExchange") t.expect(chains).toContain(entry);
    }
    t.expect(chains.endsWith(`      - name: PerplExchange\n        address: "${DEPLOYMENT.perplExchange}"\n`)).toBe(
      true,
    );
  });

  it("refuses another chain's deployment, a missing address and a contract it cannot place", (t) => {
    t.expect(() => renderConfig(configYaml, { ...DEPLOYMENT, chainId: 10_143 })).toThrow("not Mainnet");
    t.expect(() => renderConfig(configYaml, { ...DEPLOYMENT, trendrSpot: `0x${"0".repeat(40)}` })).toThrow(
      "no trendrSpot",
    );
    t.expect(() => renderConfig(configYaml, { ...DEPLOYMENT, startBlock: 0 })).toThrow("no startBlock");
    const extra = configYaml.replace(
      /^chains:/m,
      "  - name: NewContract\n    events:\n      - event: Ping()\n\nchains:",
    );
    t.expect(() => renderConfig(extra, DEPLOYMENT)).toThrow("NewContract");
  });

  it("carries the deployment's PasskeyAccount into the chain constants", (t) => {
    t.expect(renderConstants(DEPLOYMENT)).toContain(`["${DEPLOYMENT.passkeyAccount.toLowerCase()}"]`);
    t.expect(chainConstants(143)).toMatchObject({
      ausd: "0x00000000efe302beaa2b3e6e1b18d08d69a9012a",
      kuruMarginAccount: "0x2a68ba1833cdf93fa9da1eebd7f46242ad8e90c5",
    });
    t.expect(chainConstants(143).passkeyAccounts).toBe(MAINNET_PASSKEY_ACCOUNTS);
  });

  it("the committed Mainnet files match contracts/deployments/143.json", (t) => {
    if (existsSync(PATHS.deployment)) {
      const deployed = JSON.parse(readFileSync(PATHS.deployment, "utf8")) as Deployment;
      t.expect(readFileSync(PATHS.mainnetConfig, "utf8")).toBe(renderConfig(configYaml, deployed));
      t.expect(readFileSync(PATHS.constants, "utf8")).toBe(renderConstants(deployed));
    } else {
      t.expect(existsSync(PATHS.mainnetConfig)).toBe(false);
      t.expect(readFileSync(PATHS.constants, "utf8")).toBe(renderConstants(null));
    }
  });

  it("indexes Mainnet events with the generated config", async (t) => {
    const indexer = createTestIndexer();
    // The checked-in types are generated from config.yaml (Testnet), so chain 143 is untyped here.
    const process = indexer.process.bind(indexer) as unknown as (input: unknown) => Promise<unknown>;
    const trend = `0x${"11".repeat(32)}`;
    const block = (n: number) => ({ number: DEPLOYMENT.startBlock + n, timestamp: 1_791_600_000 + n });
    await process({
      chains: {
        143: {
          simulate: [
            {
              contract: "TrendRegistry",
              event: "TrendCreated",
              block: block(1),
              params: {
                id: trend,
                identifier: "topic:monad",
                assetClass: 6n,
                surfacer: "0x0000000000000000000000000000000000000051",
                index: 20_000_000n,
                observedAt: 1_791_600_001n,
              },
            },
            {
              contract: "TrendRegistry",
              event: "ReportProcessed",
              block: block(1),
              logIndex: 1,
              params: { runId: 7n, observedAt: 1_791_600_001n, created: 1n, updated: 0n, settled: 0n, rejected: 0n },
            },
          ],
        },
      },
    });
    t.expect(await indexer.Trend.getOrThrow(trend)).toMatchObject({ identifier: "topic:monad", index: 20_000_000n });
    t.expect(await indexer.Protocol.getOrThrow("trendr")).toMatchObject({ trendCount: 1, lastOracleRunId: 7n });
  });
});
